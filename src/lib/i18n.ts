export type TranslationKey = keyof typeof spanish;
export type Translator = (key: TranslationKey, params?: Record<string, string | number>) => string;

export function translate(language: Language, key: TranslationKey, params?: Record<string, string | number>): string {
  let result: string = language === "es" ? spanish[key] : key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      result = result.replaceAll("{" + name + "}", String(value));
    }
  }
  return result;
}

